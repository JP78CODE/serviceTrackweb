-- 1. Buat Tabel Utama 'services' Sesuai Modul 2 SKPL
CREATE TABLE IF NOT EXISTS public.services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    no_servis VARCHAR(30) NOT NULL UNIQUE,
    nama_pelanggan VARCHAR(100) NOT NULL,
    nama_barang VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Diterima',
    biaya_akhir DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 2. Pasang Constraint Validasi Data (Menjamin Keamanan TC-01 & TC-02 di Level Database)
ALTER TABLE public.services 
    DROP CONSTRAINT IF EXISTS check_status_valid,
    ADD CONSTRAINT check_status_valid 
        CHECK (status IN ('Diterima', 'Diperiksa', 'Diproses', 'Selesai', 'Diambil'));

ALTER TABLE public.services 
    DROP CONSTRAINT IF EXISTS check_biaya_akhir_non_negative,
    ADD CONSTRAINT check_biaya_akhir_non_negative 
        CHECK (biaya_akhir >= 0);

ALTER TABLE public.services 
    DROP CONSTRAINT IF EXISTS check_nama_pelanggan_not_empty,
    ADD CONSTRAINT check_nama_pelanggan_not_empty 
        CHECK (length(trim(nama_pelanggan)) > 0);

ALTER TABLE public.services 
    DROP CONSTRAINT IF EXISTS check_nama_barang_not_empty,
    ADD CONSTRAINT check_nama_barang_not_empty 
        CHECK (length(trim(nama_barang)) > 0);

-- 3. Aktifkan Row Level Security (RLS)
ALTER TABLE public.services ENABLE ROW LEVEL SECURITY;

-- 4. Buat Kebijakan Akses (RLS Policies) untuk Role 'anon' (Workshop / Demo Ready)
-- Kebijakan Membaca Data (SELECT)
DROP POLICY IF EXISTS "Allow anon read all services" ON public.services;
CREATE POLICY "Allow anon read all services" 
ON public.services 
FOR SELECT 
TO anon 
USING (true);

-- Kebijakan Menambahkan Data Baru (INSERT) dengan Validasi Constraint
DROP POLICY IF EXISTS "Allow anon insert services" ON public.services;
CREATE POLICY "Allow anon insert services" 
ON public.services 
FOR INSERT 
TO anon 
WITH CHECK (
    biaya_akhir >= 0 
    AND status IN ('Diterima', 'Diperiksa', 'Diproses', 'Selesai', 'Diambil')
    AND length(trim(nama_pelanggan)) > 0
    AND length(trim(nama_barang)) > 0
);

-- Kebijakan Memperbarui Data (UPDATE) dengan Validasi Constraint
DROP POLICY IF EXISTS "Allow anon update services" ON public.services;
CREATE POLICY "Allow anon update services" 
ON public.services 
FOR UPDATE 
TO anon 
USING (true)
WITH CHECK (
    biaya_akhir >= 0 
    AND status IN ('Diterima', 'Diperiksa', 'Diproses', 'Selesai', 'Diambil')
    AND length(trim(nama_pelanggan)) > 0
    AND length(trim(nama_barang)) > 0
);

-- Kebijakan Menghapus Data (DELETE)
DROP POLICY IF EXISTS "Allow anon delete services" ON public.services;
CREATE POLICY "Allow anon delete services" 
ON public.services 
FOR DELETE 
TO anon 
USING (true);

